import sympy as sym


A = sym.Matrix([[1,2,1,4],[3,8,7,20], [2,7,9,23]])

# R2-3*R1
A[1,:] = A[1,:] - 3*A[0,:]

# R3-2*R1
A[2,:] = A[2,:] - 2*A[0,:] 

# R2/2
A[1,:] = A[1,:]/2

# R3 - 3*R2
A[2,:] = A[2,:] - 3*A[1,:] 

# R2 - 2*R3 og R1 - R3
A[1,:] = A[1,:] - 2*A[2,:] 
A[0,:] = A[0,:] - A[2,:] 

# R1 -2*R2
A[0,:] = A[0,:] - 2*A[1,:] 


sym.pprint(A)


